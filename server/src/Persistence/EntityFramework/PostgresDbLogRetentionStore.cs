namespace HNMO.Persistence.EntityFramework;

using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.IO.Compression;
using System.Text.Json;
using HNMO.Interfaces;
using Npgsql;
using NpgsqlTypes;

/// <summary>
/// Persists chat log lines in PostgreSQL (<c>hnmo.chat_log</c>) and exports expired chat + audit rows
/// into compressed <c>.json.gz</c> archives prior to deleting them.
/// </summary>
public static class PostgresDbLogRetentionStore
{
    private static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = false };
    private static readonly object SchemaLock = new();
    private static string? _ensuredConnectionString;

    /// <summary>Ensures <c>hnmo.chat_log</c> exists on the target PostgreSQL database.</summary>
    /// <param name="connectionString">Npgsql connection string.</param>
    public static void EnsureSchema(string connectionString)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(connectionString);
        if (string.Equals(_ensuredConnectionString, connectionString, StringComparison.Ordinal))
        {
            return;
        }

        lock (SchemaLock)
        {
            if (string.Equals(_ensuredConnectionString, connectionString, StringComparison.Ordinal))
            {
                return;
            }

            using var conn = new NpgsqlConnection(connectionString);
            conn.Open();
            using var cmd = conn.CreateCommand();
            cmd.CommandText = """
                CREATE SCHEMA IF NOT EXISTS hnmo;
                CREATE TABLE IF NOT EXISTS hnmo.chat_log (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    time_utc TIMESTAMPTZ NOT NULL,
                    server_id INT NOT NULL,
                    map_name TEXT NOT NULL,
                    sender TEXT NOT NULL,
                    account_id UUID NOT NULL,
                    kind INT NOT NULL,
                    receiver TEXT NULL,
                    text TEXT NOT NULL
                );
                CREATE INDEX IF NOT EXISTS ix_hnmo_chat_log_time_utc ON hnmo.chat_log (time_utc);
                """;
            cmd.ExecuteNonQuery();
            _ensuredConnectionString = connectionString;
        }
    }

    /// <summary>Inserts one chat line into <c>hnmo.chat_log</c>.</summary>
    /// <param name="connectionString">Npgsql connection string.</param>
    /// <param name="timeUtc">Message timestamp (UTC).</param>
    /// <param name="serverId">Server ID.</param>
    /// <param name="mapName">Map name.</param>
    /// <param name="sender">Sender character name.</param>
    /// <param name="accountId">Sender account ID.</param>
    /// <param name="kind">Message kind integer.</param>
    /// <param name="receiver">Whisper receiver or null.</param>
    /// <param name="text">Message text.</param>
    public static void AppendChatLine(
        string connectionString,
        DateTime timeUtc,
        int serverId,
        string mapName,
        string sender,
        Guid accountId,
        int kind,
        string? receiver,
        string text)
    {
        EnsureSchema(connectionString);
        using var conn = new NpgsqlConnection(connectionString);
        conn.Open();
        using var cmd = conn.CreateCommand();
        cmd.CommandText = """
            INSERT INTO hnmo.chat_log (time_utc, server_id, map_name, sender, account_id, kind, receiver, text)
            VALUES (@t, @sid, @map, @sender, @acc, @kind, @recv, @txt);
            """;
        cmd.Parameters.Add(new NpgsqlParameter("t", NpgsqlDbType.TimestampTz) { Value = DateTime.SpecifyKind(timeUtc, DateTimeKind.Utc) });
        cmd.Parameters.AddWithValue("sid", serverId);
        cmd.Parameters.AddWithValue("map", mapName);
        cmd.Parameters.AddWithValue("sender", sender);
        cmd.Parameters.AddWithValue("acc", accountId);
        cmd.Parameters.AddWithValue("kind", kind);
        cmd.Parameters.AddWithValue("recv", (object?)receiver ?? DBNull.Value);
        cmd.Parameters.AddWithValue("txt", text);
        cmd.ExecuteNonQuery();
    }

    /// <summary>
    /// Exports chat and admin audit rows older than <paramref name="cutoffUtc"/> to a verified <c>.json.gz</c>
    /// file in <paramref name="archiveDirectory"/> and only deletes them after the archive is written cleanly.
    /// </summary>
    /// <param name="connectionString">PostgreSQL connection string.</param>
    /// <param name="cutoffUtc">Rows older than this UTC time are exported and deleted.</param>
    /// <param name="archiveDirectory">Output folder for compressed exports.</param>
    /// <param name="utcNow">Optional UTC timestamp.</param>
    /// <returns>Summary of exported/deleted rows and archive path.</returns>
    public static DbLogPurgeResult ExportAndPurgePostgres(
        string connectionString,
        DateTime cutoffUtc,
        string archiveDirectory,
        DateTimeOffset? utcNow = null)
    {
        EnsureSchema(connectionString);
        cutoffUtc = DateTime.SpecifyKind(cutoffUtc, DateTimeKind.Utc);
        using var conn = new NpgsqlConnection(connectionString);
        conn.Open();

        var chatRows = new List<object>();
        using (var cmd = conn.CreateCommand())
        {
            cmd.CommandText = """
                SELECT id, time_utc, server_id, map_name, sender, account_id, kind, receiver, text
                FROM hnmo.chat_log
                WHERE time_utc < @cutoff
                ORDER BY id;
                """;
            cmd.Parameters.Add(new NpgsqlParameter("cutoff", NpgsqlDbType.TimestampTz) { Value = cutoffUtc });
            using var reader = cmd.ExecuteReader();
            while (reader.Read())
            {
                chatRows.Add(new
                {
                    id = reader.GetInt64(0),
                    timeUtc = reader.GetDateTime(1).ToUniversalTime(),
                    serverId = reader.GetInt32(2),
                    mapName = reader.GetString(3),
                    sender = reader.GetString(4),
                    accountId = reader.GetGuid(5),
                    kind = reader.GetInt32(6),
                    receiver = reader.IsDBNull(7) ? null : reader.GetString(7),
                    text = reader.GetString(8),
                });
            }
        }

        var auditRows = new List<object>();
        var auditTableExists = TableExists(conn, "admin", "AdminAuditEntry");
        if (auditTableExists)
        {
            using var cmd = conn.CreateCommand();
            cmd.CommandText = """
                SELECT "Id", "StartedAt", "CompletedAt", "Username", "Role", "Action", "Outcome"
                FROM admin."AdminAuditEntry"
                WHERE "StartedAt" < @cutoff
                ORDER BY "StartedAt";
                """;
            cmd.Parameters.Add(new NpgsqlParameter("cutoff", NpgsqlDbType.TimestampTz) { Value = cutoffUtc });
            using var reader = cmd.ExecuteReader();
            while (reader.Read())
            {
                auditRows.Add(new
                {
                    id = reader.GetGuid(0),
                    startedAtUtc = reader.GetDateTime(1).ToUniversalTime(),
                    completedAtUtc = reader.IsDBNull(2) ? (DateTime?)null : reader.GetDateTime(2).ToUniversalTime(),
                    username = reader.GetString(3),
                    role = reader.GetString(4),
                    action = reader.GetString(5),
                    outcome = reader.GetString(6),
                });
            }
        }

        if (chatRows.Count == 0 && auditRows.Count == 0)
        {
            return new DbLogPurgeResult(0, 0, null);
        }

        var archivePath = WriteCompressedExport(archiveDirectory, cutoffUtc, chatRows, auditRows, utcNow ?? DateTimeOffset.UtcNow);
        if (!File.Exists(archivePath) || new FileInfo(archivePath).Length == 0)
        {
            throw new IOException($"Aborting database log delete: export archive was not written to {archivePath}.");
        }

        using var tx = conn.BeginTransaction();
        var deletedChat = 0;
        if (chatRows.Count > 0)
        {
            using var del = conn.CreateCommand();
            del.Transaction = tx;
            del.CommandText = "DELETE FROM hnmo.chat_log WHERE time_utc < @cutoff;";
            del.Parameters.Add(new NpgsqlParameter("cutoff", NpgsqlDbType.TimestampTz) { Value = cutoffUtc });
            deletedChat = del.ExecuteNonQuery();
        }

        var deletedAudit = 0;
        if (auditRows.Count > 0 && auditTableExists)
        {
            using var del = conn.CreateCommand();
            del.Transaction = tx;
            del.CommandText = "DELETE FROM admin.\"AdminAuditEntry\" WHERE \"StartedAt\" < @cutoff;";
            del.Parameters.Add(new NpgsqlParameter("cutoff", NpgsqlDbType.TimestampTz) { Value = cutoffUtc });
            deletedAudit = del.ExecuteNonQuery();
        }

        tx.Commit();
        return new DbLogPurgeResult(deletedChat, deletedAudit, archivePath);
    }

    /// <summary>
    /// Exports arbitrary in-memory or EF log collections to a verified <c>.json.gz</c> file before invoking <paramref name="deleteAfterExport"/>.
    /// </summary>
    /// <typeparam name="TChat">Chat item type.</typeparam>
    /// <typeparam name="TAudit">Audit item type.</typeparam>
    /// <param name="archiveDirectory">Archive directory.</param>
    /// <param name="cutoffUtc">Cutoff timestamp (UTC).</param>
    /// <param name="chatRows">Expired chat rows to archive.</param>
    /// <param name="auditRows">Expired audit rows to archive.</param>
    /// <param name="deleteAfterExport">Deletion delegate run ONLY after the compressed archive is safely written.</param>
    /// <param name="utcNow">Optional UTC clock.</param>
    /// <returns>Purge summary.</returns>
    public static DbLogPurgeResult ExportBeforeDelete<TChat, TAudit>(
        string archiveDirectory,
        DateTime cutoffUtc,
        IReadOnlyList<TChat> chatRows,
        IReadOnlyList<TAudit> auditRows,
        Action deleteAfterExport,
        DateTimeOffset? utcNow = null)
    {
        if (chatRows.Count == 0 && auditRows.Count == 0)
        {
            return new DbLogPurgeResult(0, 0, null);
        }

        var archivePath = WriteCompressedExport(archiveDirectory, cutoffUtc, chatRows, auditRows, utcNow ?? DateTimeOffset.UtcNow);
        if (!File.Exists(archivePath) || new FileInfo(archivePath).Length == 0)
        {
            throw new IOException($"Aborting log delete: export archive was not written to {archivePath}.");
        }

        deleteAfterExport();
        return new DbLogPurgeResult(chatRows.Count, auditRows.Count, archivePath);
    }

    /// <summary>Registers a PostgreSQL exporter with <see cref="DbLogRetentionRegistry"/>.</summary>
    /// <param name="connectionString">PostgreSQL connection string.</param>
    public static void RegisterExporter(string connectionString)
    {
        DbLogRetentionRegistry.Current = new PostgresExporter(connectionString);
    }

    private static string WriteCompressedExport(string archiveDirectory, DateTime cutoffUtc, object chatRows, object auditRows, DateTimeOffset utcNow)
    {
        Directory.CreateDirectory(archiveDirectory);
        var stamp = ControlOperations.FormatSydneyTime(utcNow)
            .Replace("-", string.Empty, StringComparison.Ordinal)
            .Replace(" ", "-", StringComparison.Ordinal)
            .Replace(":", string.Empty, StringComparison.Ordinal);
        var archivePath = Path.Combine(archiveDirectory, $"db-logs-{stamp}.json.gz");
        var tempPath = archivePath + ".tmp";
        var payload = new
        {
            exportedAtUtc = utcNow.UtcDateTime,
            exportedAtSydney = ControlOperations.FormatSydneyTime(utcNow),
            cutoffUtc = DateTime.SpecifyKind(cutoffUtc, DateTimeKind.Utc),
            chatLogs = chatRows,
            auditEntries = auditRows,
        };

        using (var fs = new FileStream(tempPath, FileMode.Create, FileAccess.Write, FileShare.None))
        using (var gzip = new GZipStream(fs, CompressionLevel.Optimal))
        {
            JsonSerializer.Serialize(gzip, payload, JsonOptions);
        }

        File.Move(tempPath, archivePath, overwrite: true);
        return archivePath;
    }

    private static bool TableExists(NpgsqlConnection conn, string schema, string table)
    {
        using var cmd = conn.CreateCommand();
        cmd.CommandText = """
            SELECT EXISTS (
                SELECT 1
                FROM information_schema.tables
                WHERE table_schema = @s AND table_name = @t
            );
            """;
        cmd.Parameters.AddWithValue("s", schema);
        cmd.Parameters.AddWithValue("t", table);
        return cmd.ExecuteScalar() is bool b && b;
    }

    private sealed class PostgresExporter(string connectionString) : IDbLogRetentionExporter
    {
        public DbLogPurgeResult ExportAndPurgeOlderThan(DateTime cutoffUtc, string archiveDirectory) =>
            ExportAndPurgePostgres(connectionString, cutoffUtc, archiveDirectory);
    }
}
