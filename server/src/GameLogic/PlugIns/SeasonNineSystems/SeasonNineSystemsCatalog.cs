    /// <summary>Muun companion definition.</summary>
    public readonly record struct MuunSpec(
        int Id,
        byte ItemGroup,
        short ItemNumber,
        byte MuunType,
        byte MaxRank,
        int OptionIndex,
        byte AddOptionType,
        int AddOptionValue,
        int EvolutionItemGroup,
        short EvolutionItemNumber,
        int SkillDelayMs,
        string Name,
        string StartDate = "",
        string EndDate = "");

    /// <summary>Muun option scaling &amp; condition definition.</summary>
    public readonly record struct MuunOptionSpec(
        int Index,
        int OptionType,
        int ValueEvolved,
        int ValueLv1,
        int ValueLv2,
        int ValueLv3,
        int ValueLv4,
        int ValueLv5,
        int ConditionType,
        int ConditionValue1,
        int ConditionValue2,
        string Name);

    /// <summary>Pentagram item option slot linkage.</summary>
    public readonly record struct PentagramSpec(
        byte ItemGroup,
        short ItemNumber,
        byte Grade,
        int OptionNum1,
        int OptionNum2,
        int OptionNum3,
        string Name);

    /// <summary>Errtel socket bonus definition across levels 0..10 with exact level values and upgrade rates.</summary>
    public readonly record struct ErrtelOptionSpec(
        int Index,
        byte ItemGroup,
        short ItemNumber,
        byte Rank,
        int OptionNum,
        int OptionRate,
        int ValueLv0,
        int ValueLv5,
        int ValueLv10,
        string Name,
        int[] Values,
        int[] MixRates);

    /// <summary>Errtel extraction base success rate (n/10000) by rank and level.</summary>
    public readonly record struct ErrtelExtractRateSpec(int Id, byte Rank, byte Level, int RateOutOf10000);

    /// <summary>Pentagram / Errtel mix recipe from PentagramMixNeedSource.bmd.</summary>
    public readonly record struct PentagramMixSpec(
        byte Category,
        int RecipeId,
        int RateOutOf10000,
        int Zen,
        byte RequiredLevel,
        byte Flag21,
        byte Flag22,
        string Materials);

    /// <summary>Pentagram combo option definition from PentagramOption_eng.bmd.</summary>
    public readonly record struct PentagramComboOptionSpec(
        int OptionNum,
        string Name,
        string Requirements);

