// Generates src/game/legacyQuestDialog.generated.ts: the class change quests' NPC dialogs as the desktop
// client keeps them (GameLogic/Quests/DialogStructure.cpp: each dialog's replies, where a reply leads and
// the answer code it sends; the texts from Localization/Dialog.en.resx).
//
// Usage: node tools/generate-quest-dialog.mjs <the HNMO desktop client folder (client/src)>

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { XMLParser } from 'fast-xml-parser';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT = path.join(HERE, '..', 'src', 'game', 'legacyQuestDialog.generated.ts');

const clientDir = process.argv[2];
const structureFile = clientDir && path.join(clientDir, 'source', 'GameLogic', 'Quests', 'DialogStructure.cpp');
const textFile = clientDir && path.join(clientDir, 'Localization', 'Dialog.en.resx');
if (!structureFile || !fs.existsSync(structureFile) || !fs.existsSync(textFile)) {
  console.error('Usage: node tools/generate-quest-dialog.mjs <the HNMO desktop client folder (client/src)>');
  process.exit(1);
}

const parser = new XMLParser({ ignoreAttributes: false, attributeNamePrefix: '', isArray: (name) => name === 'data' });
const resx = parser.parse(fs.readFileSync(textFile, 'utf8'));
const texts = new Map(resx.root.data.map((entry) => [entry.name, String(entry.value ?? '')]));
// I18N::Dialog::Text50 -> Text_50, Answer53Slot1 -> Answer_53_Slot_1
const textOf = (key) => {
  if (!key) return null;
  const name = key.replace(/^Text(\d+)$/, 'Text_$1').replace(/^Answer(\d+)Slot(\d+)$/, 'Answer_$1_Slot_$2');
  return texts.get(name) ?? '';
};

const dialogs = {};
for (const line of fs.readFileSync(structureFile, 'utf8').split('\n')) {
  const match = line.match(/^\s*\{(\d+),\s*\{(.*)\},\s*(?:&I18N::Dialog::(\w+)|nullptr)\},\s*\/\/ idx (\d+)/);
  if (!match) continue;
  const [, count, branches, textKey, index] = match;
  const answers = [...branches.matchAll(/\{(-?\d+),\s*(-?\d+),\s*&I18N::Dialog::(\w+)\}/g)]
    .map(([, link, returnCode, key]) => ({ link: Number(link), returnCode: Number(returnCode), text: textOf(key) }));
  if (!textKey && answers.length === 0) continue;
  dialogs[index] = { numAnswer: Number(count), text: textOf(textKey) ?? '', answers };
}

const header = `// Generated by tools/generate-quest-dialog.mjs from the desktop client's DialogStructure.cpp and
// Localization/Dialog.en.resx. Don't edit.

export interface LegacyDialogAnswer { link: number; returnCode: number; text: string }
export interface LegacyDialog { numAnswer: number; text: string; answers: LegacyDialogAnswer[] }

`;
fs.writeFileSync(OUTPUT, `${header}export const LEGACY_DIALOGS: Record<number, LegacyDialog> = ${JSON.stringify(dialogs, null, 1)};\n`);
console.log(`${Object.keys(dialogs).length} dialogs -> ${path.relative(process.cwd(), OUTPUT)}`);
